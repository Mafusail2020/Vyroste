def main() -> None:
    # Remove existing seeds to avoid duplicates
    existing = sb.table("blog_posts").select("title").execute()
    existing_titles = {r["title"] for r in (existing.data or [])}

    to_insert = [p for p in POSTS if p["title"] not in existing_titles]
    if not to_insert:
        print("All posts already seeded — nothing to do.")
        return

    result = sb.table("blog_posts").insert(to_insert).execute()
    print(f"Inserted {len(result.data)} blog posts:")
    for p in result.data:
        print(f"  [{p['category']}] {p['title'][:60]}...")


if __name__ == "__main__":
    main()
